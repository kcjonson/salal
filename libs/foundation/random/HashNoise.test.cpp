// At lacunarity 2, octave p's lattice points sit at 2^(q-p) * offset(p) - offset(q)
// in octave q's cells, on each axis; that has to stay off the integers for every
// pair, octaves past 16 included (they reuse the table), and so does each offset.
TEST(HashNoiseTests, OctaveOffsetsKeepLatticesApart) {
	constexpr int64_t kOne = 65536;
	constexpr int64_t kMargin = kOne / 32;
	auto			  distanceFromInteger = [](int64_t numerator) {
		 const int64_t r = ((numerator % kOne) + kOne) % kOne;
		 return std::min(r, kOne - r);
	};
	for (const auto& table : {detail::kOctaveOffsetX, detail::kOctaveOffsetY}) {
		for (int p = 0; p < 16; ++p) {
			EXPECT_GE(distanceFromInteger(table[p]), kMargin) << "p=" << p;
			for (int q = 0; q < 16; ++q) {
				if (p == q) {
					continue;
				}
				const int shift = (q - p + 16) % 16;
				EXPECT_GE(distanceFromInteger((int64_t{table[p]} << shift) - table[q]), kMargin) << "p=" << p << " q=" << q;
			}
		}
	}
}

